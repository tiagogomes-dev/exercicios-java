public class Operadores {
public static void main(String [] args) {

    int x = 7;
    int y = 2;

    System.out.println("x / y = " + x / y);
    System.out.println("x % y = " + x % y);
    System.out.println("x++ = " + (x++));
    System.out.println("x = " + x);
    System.out.println("++x = " + (++x));
    x += 5;
    System.out.println("x = " + x);
}
}
