public class FichaDoAluno {
public static void main(String [] args) {

    int idade = 17;                 // int = número inteiro
    double altura = 1.72;           // double = número decimal
    char inicial = 'A';             // char = um único caractere
    boolean matricula = true;       // boolean = verdadeiro ou falso
    String nomeCompleto = "Ana";   // String = texto

    System.out.println("Idade do aluno: " + idade);
    System.out.println("Altura do aluno: " + altura + " metros");
    System.out.println("Inicial do nome do aluno: " + inicial);
    System.out.println("Aluno está matriculado? " + matricula);
    System.out.println("Nome completo do aluno: " + nomeCompleto);
}
}
